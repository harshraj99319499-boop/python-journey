# 1. sorted(): List ko bina badle tarteeb (order) me lana
scores = [40, 10, 30, 20]
print("Sorted scores:", sorted(scores))

# 2. any(): Kya koi EK bhi shart True hai?
conditions = [False, False, True]
print("Is any condition True?:", any(conditions))

# 3. all(): Kya SAARI shartein True hain?
print("Are all conditions True?:", all(conditions))
