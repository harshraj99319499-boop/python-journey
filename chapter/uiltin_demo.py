# Chapter 3: Built-in Functions Demo

# 1. Inspection & Length
name = "Python"
print("Data type of name:", type(name))
print("Length of name:", len(name))

# 2. Mathematical Functions
numbers = [5, 12, 3, 20]
print("Smallest number (min):", min(numbers))
print("Largest number (max):", max(numbers))
print("Sum of numbers (sum):", sum(numbers))

# Rounding and Absolute value
print("Absolute of -15 (abs):", abs(-15))
print("Round 4.67 (round):", round(4.67))

# 3. Type Conversion
text_num = "50"
real_num = int(text_num)
print("Converted string to integer:", real_num + 10)
